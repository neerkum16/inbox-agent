-- ============================================================================
-- BANKDB - DATA LOAD
-- ============================================================================
-- Purpose:
--   Load generated BANKDB CSV files into PostgreSQL tables.
------------------------------------------------------------

-- Run from project root:
--   psql -U postgres -d bankdb -f database/load_data.sql
---------------------------------------------------------

-- Notes:
--   - Uses \copy so files are read by the local psql client.
--   - CSV column lists explicitly match the PostgreSQL schema.
--   - Identity columns are generated automatically by PostgreSQL.
--   - Tables are loaded in dependency order.
-- ============================================================================

\set ON_ERROR_STOP on

\echo
\echo ============================================================
\echo BANKDB DATA LOAD
\echo ============================================================
\echo

BEGIN;

-- ============================================================================
-- 1. REASON_CODE
-- Reference/master data.
-- ============================================================================

\echo Loading REASON_CODE...

\copy reason_code (reason_code, applies_to, description, customer_facing_text) FROM 'database/output/reason_code.csv' WITH (FORMAT csv, HEADER true);

-- ============================================================================
-- 2. CUSTOMER
-- Parent entity.
-- ============================================================================

\echo Loading CUSTOMER...

\copy customer (sort_code, customer_number, customer_name, customer_address, customer_city, customer_state, customer_postcode, customer_email, customer_phone, date_of_birth, credit_score, credit_score_review_date, customer_status, status_reason, status_changed_at, created_at, updated_at) FROM 'database/output/customer.csv' WITH (FORMAT csv, HEADER true);

-- ============================================================================
-- 3. ACCOUNT
-- Depends on CUSTOMER.
-- ============================================================================

\echo Loading ACCOUNT...

\copy account (sort_code, account_number, customer_number, account_type, interest_rate, opened_date, account_status, status_reason, status_changed_at, closed_date, overdraft_limit, last_statement_date, next_statement_date, available_balance, actual_balance, created_at, updated_at) FROM 'database/output/account.csv' WITH (FORMAT csv, HEADER true);

-- ============================================================================
-- 4. STATUS_HISTORY
-- history_id is GENERATED ALWAYS AS IDENTITY and is generated by PostgreSQL.
-- ============================================================================

\echo Loading STATUS_HISTORY...

\copy status_history (entity_type, sort_code, entity_number, previous_status, status_reason, new_status, changed_at) FROM 'database/output/status_history.csv' WITH (FORMAT csv, HEADER true);

-- ============================================================================
-- 5. TRANSACTION_HISTORY
-- transaction_id is GENERATED ALWAYS AS IDENTITY and is generated by PostgreSQL.
-- customer_number is now populated on every event (including account-level
-- ones) and must be listed here to match transaction_history_generator.py's
-- CSV header and the updated schema's NOT NULL/FK column.
-- ============================================================================

\echo Loading TRANSACTION_HISTORY...

\copy transaction_history (sort_code, account_number, customer_number, transaction_timestamp, transaction_type, transaction_amount, transaction_description, status_code, status_reason, created_at) FROM 'database/output/transaction_history.csv' WITH (FORMAT csv, HEADER true);

-- ============================================================================
-- 6. CONTROL
-- Generated control totals and metadata.
-- ============================================================================

\echo Loading CONTROL...

\copy control (control_key, control_value, description, created_at, updated_at) FROM 'database/output/control.csv' WITH (FORMAT csv, HEADER true);

COMMIT;

\echo
\echo ============================================================
\echo DATA LOAD COMPLETED SUCCESSFULLY
\echo ============================================================
\echo

-- ============================================================================
-- LOAD SUMMARY
-- ============================================================================

SELECT
table_name,
row_count
FROM (
SELECT 'customer' AS table_name, COUNT(*) AS row_count FROM customer
UNION ALL
SELECT 'account', COUNT(*) FROM account
UNION ALL
SELECT 'reason_code', COUNT(*) FROM reason_code
UNION ALL
SELECT 'status_history', COUNT(*) FROM status_history
UNION ALL
SELECT 'transaction_history', COUNT(*) FROM transaction_history
UNION ALL
SELECT 'control', COUNT(*) FROM control
) counts
ORDER BY table_name;

\echo
\echo ============================================================
\echo LOAD SUMMARY COMPLETED
\echo ============================================================
