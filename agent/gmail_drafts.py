"""
GMAIL DRAFT CREATION - PHASE 5A / PHASE 5C SEND PREPARATION
================================

This module contains the Gmail-specific operation for creating a draft reply.

IMPORTANT
---------
Creating a draft is the ONLY Gmail write operation introduced in Phase 5A.

This module does NOT:
    - send the draft
    - mark the source message as read
    - archive the source message
    - change labels
    - delete the source message

The banking business logic remains in agent.pipeline. This module only takes
an already-generated draft reply and turns it into a Gmail draft resource.
"""

# base64 is used because the Gmail API expects the MIME message in
# URL-safe base64 format in the message.raw field.
import base64

# EmailMessage is Python's standard-library helper for constructing a valid
# RFC 5322/MIME email message.
from email.message import EmailMessage


# =============================================================================
# SUBJECT HELPER
# =============================================================================

def build_reply_subject(original_subject):
    """
    Build the subject for a reply draft.

    If the original subject already starts with Re:, do not add another one.
    """

    subject = (original_subject or "").strip()

    if subject.lower().startswith("re:"):
        return subject

    if subject:
        return "Re: " + subject

    return "Re: Your enquiry"


# =============================================================================
# MIME MESSAGE BUILDER
# =============================================================================

def build_reply_message(
    from_address,
    original_subject,
    draft_reply,
    rfc_message_id=None,
    references=None,
    outbound_message_id=None,
):
    """
    Build the MIME message that will become the Gmail draft.

    Parameters
    ----------
    from_address:
        The sender of the original inbound message. The draft is addressed
        back to this person.

    original_subject:
        Subject of the inbound message.

    draft_reply:
        The response text generated by the banking pipeline.

    rfc_message_id:
        The original RFC Message-ID. When available, it is used for
        In-Reply-To so Gmail/email clients can preserve conversation threading.

    references:
        Existing References header value, when available.

    outbound_message_id:
        Optional deterministic RFC Message-ID assigned to an autonomous reply.
        Phase 5C uses this value as a durable send/retry correlation key.
    """

    if not from_address:
        raise ValueError(
            "Cannot create a Gmail draft because the inbound message has no "
            "sender email address."
        )

    if draft_reply is None or not str(draft_reply).strip():
        raise ValueError(
            "Cannot create a Gmail draft because the draft reply is empty."
        )

    message = EmailMessage()

    # The From address identifies the authenticated Gmail mailbox conceptually.
    # Gmail will apply the actual account identity when the draft is created.
    message["To"] = from_address
    message["Subject"] = build_reply_subject(original_subject)

    if outbound_message_id:
        message["Message-ID"] = outbound_message_id

    # These headers are what make this an email reply rather than an unrelated
    # new message when the original RFC Message-ID is available.
    if rfc_message_id:
        message["In-Reply-To"] = rfc_message_id

        if references:
            message["References"] = references + " " + rfc_message_id
        else:
            message["References"] = rfc_message_id

    message.set_content(str(draft_reply).strip())

    return message


# =============================================================================
# GMAIL DRAFT CREATION
# =============================================================================

def create_gmail_draft(
    service,
    user_id,
    message,
    draft_reply,
    outbound_message_id=None,
):
    """
    Create a Gmail draft reply and return the Gmail draft resource.

    This function calls only:

        users.drafts.create

    It does NOT call Gmail send, modify, delete, or message-modification APIs.

    The source Gmail thread ID is supplied to Gmail so the draft belongs to
    the same conversation when Gmail accepts the thread association.
    """

    mime_message = build_reply_message(
        from_address=message.from_address,
        original_subject=message.subject,
        draft_reply=draft_reply,
        rfc_message_id=message.rfc_message_id,
        references=(message.headers or {}).get("References") if message.headers else None,
        outbound_message_id=outbound_message_id,
    )

    # Gmail API expects URL-safe base64 without needing normal MIME line
    # handling to be performed by the caller.
    raw_message = base64.urlsafe_b64encode(
        mime_message.as_bytes()
    ).decode("utf-8")

    gmail_message = {
        "raw": raw_message,
    }

    # Thread ID is optional because the normalized contract permits None.
    # When available, it lets Gmail associate the draft with the original
    # conversation explicitly.
    if message.source_thread_id:
        gmail_message["threadId"] = message.source_thread_id

    draft_body = {
        "message": gmail_message,
    }

    return (
        service.users()
        .drafts()
        .create(
            userId=user_id,
            body=draft_body,
        )
        .execute()
    )
